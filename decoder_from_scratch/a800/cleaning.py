"""数据清洗规则（纯标准库，在数据下载子进程里逐条运行）。

分四类文本：zh（中文网页/行业语料）、en（英文教育网页/合成教材）、code（源代码）、math（数学网页）。
规则是可扩展到上百亿字符的启发式过滤，不是逐篇人工审查；每个来源抽样写入 data/samples/ 供人工抽查。

另一个重要步骤是**中文标点统一**：不同来源的中文标点风格不一致（IndustryCorpus 全用半角 ","，
CCI3-HQ 是半角逗号 + 全角句号），Mac 上那次训练就因为训练数据里没有全角"，"，提示词以"，"结尾时模型输出乱码。
这里统一把"紧挨汉字的 ASCII 标点"改成全角，推理时对提示词做同样的处理（见 normalize_zh_punct）。
"""

from collections import Counter
import hashlib
import re
import unicodedata
import zlib

CJK = r'一-鿿㐀-䶿'
_HALF_TO_FULL = {',': '，', '.': '。', ';': '；', ':': '：', '!': '！', '?': '？', '(': '（', ')': '）'}
# ASCII 标点：左边是汉字（或左右都是汉字/中文标点）时转全角；"3.5"、"a.b" 等两边是 ASCII 的不动。
_PUNCT_AFTER_CJK = re.compile(rf'(?<=[{CJK}”’》」）])\s?([,.;:!?()])')
_PUNCT_BEFORE_CJK = re.compile(rf'([,;:!?(])\s?(?=[{CJK}“‘《「（])')
_ELLIPSIS = re.compile(rf'(?<=[{CJK}])\.{{3,}}|\.{{3,}}(?=[{CJK}])')
_FULL_COMMON = str.maketrans({'　': ' '})


def normalize_zh_punct(text):
    """中文语境下的半角标点转全角；英文、代码、数字中的标点保持原样。训练和推理用同一个函数。"""
    if not re.search(f'[{CJK}]', text):
        return text
    text = _ELLIPSIS.sub('……', text)
    text = _PUNCT_AFTER_CJK.sub(lambda m: _HALF_TO_FULL[m.group(1)], text)
    text = _PUNCT_BEFORE_CJK.sub(lambda m: _HALF_TO_FULL[m.group(1)], text)
    # "汉字." 后面若是数字列表（如 "第一条.1"）也已被转换，属于可接受的少量误差
    return text


SPAM = re.compile(
    r'博彩|百家乐|娱乐城|送彩金|老虎机|投注|代开发票|加微信|加QQ|扫码领取|亚搏|开云体育|开元体育|必威|买球|'
    r'真人娱乐|六合彩|特码|开奖结果|色情|成人视频|av女优|无码|裸聊|'
    r'\b(?:online casino|viagra|cialis|porn|pornography|escort service|payday loans?)\b', re.I)
NAV = re.compile(
    r'^(?:上一篇|下一篇|相关阅读|相关推荐|推荐阅读|责任编辑|本文来源|文章来源|版权声明|免责声明|分享至|点击上方|'
    r'关注公众号|阅读原文|返回首页|收藏本站|相关文章|热门推荐|原标题|图片来源|'
    r'Share this|Related posts?|Read more|Click here|Subscribe|Copyright|All rights reserved|Previous post|Next post)'
    r'.{0,120}$', re.I)
PROMO = re.compile(r'品牌推广|市场占有率|企业资质|招商加盟|欢迎咨询|销售热线|咨询热线|厂家直销|欢迎选购|特价促销|优惠券')
MARKUP = re.compile(r'<(?:div|script|iframe|span|table|style)\b|&nbsp;|&lt;|&gt;|\[img\]', re.I)
FORTUNE = re.compile(r'八字.{0,8}(?:喜神|大运|忌神)|风水大师|算命|星座运势')
CODE_AUTOGEN = re.compile(r'auto-?generated|generated by|do not edit|<auto-generated', re.I)


def canonical(text):
    return re.sub(r'\s+', ' ', unicodedata.normalize('NFKC', text)).strip()


def doc_hash64(text):
    """规范化文本的 64 位哈希：用于去重与按哈希划分 train/val/test（同一文档永远落在同一划分）。"""
    return int.from_bytes(hashlib.blake2b(canonical(text).encode('utf-8'), digest_size=8).digest(), 'big')


def paragraph_hashes(text, min_len=40):
    out = []
    for line in text.split('\n'):
        line = canonical(line)
        if len(line) >= min_len:
            out.append(int.from_bytes(hashlib.blake2b(line.encode('utf-8'), digest_size=8).digest(), 'big'))
    return out


def _strip_boilerplate(text):
    kept = []
    for line in text.split('\n'):
        stripped = line.strip()
        if len(stripped) <= 160 and NAV.match(stripped):
            continue
        if kept and 10 <= len(stripped) <= 200 and stripped == kept[-1].strip():
            continue
        kept.append(line.rstrip())
    return re.sub(r'\n{3,}', '\n\n', '\n'.join(kept)).strip()


def _repetitive(text):
    raw = text.encode('utf-8')
    if len(raw) >= 600 and len(zlib.compress(raw)) / len(raw) < 0.15:
        return True  # 可压缩性过高 = 大量重复（自然语言通常在 0.3 以上）
    lines = [x.strip() for x in text.split('\n') if x.strip()]
    counts = Counter(lines)
    if sum((n - 1) * len(s) for s, n in counts.items() if len(s) >= 15) > len(text) * 0.2:
        return True
    if len(text) >= 600:
        grams = Counter(text[i:i + 30] for i in range(0, len(text) - 30, 15))
        if grams and grams.most_common(1)[0][1] >= 8:
            return True
    return False


def clean_text(text, kind, min_chars=None, max_chars=100_000):
    """返回 (清洗后文本, None) 或 (None, 拒绝原因)。kind ∈ {zh, en, code, math}。"""
    if not isinstance(text, str):
        return None, 'not_text'
    if '�' in text or '\x00' in text:
        return None, 'corruption'
    text = unicodedata.normalize('NFC', text).replace('\r\n', '\n').replace('\r', '\n')
    if kind == 'code':
        return _clean_code(text, max_chars)
    min_chars = min_chars or (200 if kind == 'zh' else 400)
    if len(text) < min_chars:
        return None, 'too_short'
    if len(text) > max_chars:
        text = text[:max_chars].rsplit('\n', 1)[0]  # 超长文档截断到段落边界，而不是整篇丢弃
    if SPAM.search(text):
        return None, 'spam'
    if kind != 'math' and MARKUP.search(text):
        return None, 'markup'
    if kind == 'zh':
        text = text.translate(_FULL_COMMON)
        if len(PROMO.findall(text)) >= 2:
            return None, 'promotion'
        if FORTUNE.search(text):
            return None, 'fortune'
    text = _strip_boilerplate(text)
    if len(text) < min_chars:
        return None, 'too_short_after_clean'
    if kind == 'zh':
        if sum('一' <= c <= '鿿' for c in text) / len(text) < 0.3:
            return None, 'language'
        text = normalize_zh_punct(text)
        if len(re.findall(r'[。！？]', text)) < 2:
            return None, 'fragment'
    else:
        letters = sum(c.isascii() and c.isalpha() for c in text) / len(text)
        if letters < (0.3 if kind == 'math' else 0.5):
            return None, 'language'
        if len(re.findall(r'[.!?]', text)) < 3:
            return None, 'fragment'
    if _repetitive(text):
        return None, 'repetition'
    return text, None


def _clean_code(text, max_chars):
    """代码：长度、行长、字母比例、自动生成文件、重复内容。参考 StarCoder / The Stack 的常用过滤。"""
    if not 100 <= len(text) <= max_chars:
        return None, 'code_length'
    lines = text.split('\n')
    if max(len(line) for line in lines) > 1000:
        return None, 'code_long_line'
    if sum(len(line) for line in lines) / len(lines) > 120:
        return None, 'code_avg_line'
    if sum(c.isalpha() for c in text) / len(text) < 0.25:
        return None, 'code_alpha'
    if CODE_AUTOGEN.search(text[:2000]):
        return None, 'code_autogen'
    if _repetitive(text):
        return None, 'repetition'
    return text, None
